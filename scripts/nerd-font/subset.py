"""Rebuilds the modlist icon font from Symbols Nerd Font.

Inputs (download them yourself from https://github.com/ryanoasis/nerd-fonts/releases):
  * SymbolsNerdFont-Regular.ttf from NerdFontsSymbolsOnly.zip
  * glyphnames.json from the nerd-fonts repository (same release)

Usage (needs `pip install fonttools brotli`):
  python scripts/nerd-font/subset.py path/to/SymbolsNerdFont-Regular.ttf path/to/glyphnames.json

Writes ui/src/assets/fonts/symbols-nerd-font-subset.woff2 and ui/src/features/modlists/nerdIcons.ts
with only the glyphs listed in icons.txt. Only use Font Awesome (fa-) and Material Design (md-)
glyphs, so ui/public/licenses/SymbolsNerdFont.txt stays correct.
"""

import json
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent


def label(name: str) -> str:
    return name.split("-", 1)[1].replace("_", " ").capitalize()


def main(ttf: str, glyphnames: str) -> None:
    names = [l.strip() for l in (HERE / "icons.txt").read_text().splitlines() if l.strip() and not l.startswith("#")]
    bad = [n for n in names if not n.startswith(("fa-", "md-"))]
    if bad:
        sys.exit(f"Only fa- and md- glyphs are allowed: {bad}")
    table = json.loads(Path(glyphnames).read_text(encoding="utf8"))
    font = TTFont(ttf)
    cmap = font.getBestCmap()
    icons = []
    for n in names:
        if n not in table or int(table[n]["code"], 16) not in cmap:
            sys.exit(f"Not in the font: {n}")
        icons.append((n, int(table[n]["code"], 16)))

    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = []
    opts.name_IDs = ["*"]
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=[c for _, c in icons])
    sub.subset(font)
    font.flavor = "woff2"
    out = ROOT / "ui/src/assets/fonts/symbols-nerd-font-subset.woff2"
    out.parent.mkdir(parents=True, exist_ok=True)
    font.save(out)

    lines = [
        "// Generated by scripts/nerd-font/subset.py. Do not edit; change icons.txt and rerun.",
        "",
        "/** Icons in the bundled Symbols Nerd Font subset: [name, label, code point]. */",
        "export const NERD_ICONS: readonly (readonly [name: string, label: string, codePoint: number])[] = [",
    ]
    lines += [f'  ["{n}", "{label(n)}", 0x{c:x}],' for n, c in icons]
    lines += ["];", ""]
    (ROOT / "ui/src/features/modlists/nerdIcons.ts").write_text("\n".join(lines), newline="\n")
    print(f"{len(icons)} icons, {out.stat().st_size} bytes")


if __name__ == "__main__":
    main(*sys.argv[1:3])
